export default function AIEnrichment({ ai }) {
  if (!ai?.current)
    return (
      <section className="ai-panel">
        <h2>
          {ai?.status === 'PROCESSING' ? 'AI analysis in progress' : 'AI analysis not available'}
        </h2>
        <p>
          {ai?.skipReason ||
            (ai?.status === 'FAILED'
              ? 'Analysis did not complete. The source description is still available above.'
              : 'This item has not been analyzed yet. The description above is original source metadata.')}
        </p>
        <small>Topics use source metadata rules until validated AI analysis is saved.</small>
      </section>
    );
  return (
    <section className="ai-panel">
      <h2>AI summary</h2>
      <p>{ai.summary || 'The available evidence did not support a summary for this item.'}</p>
      <small>
        {ai.scope === 'abstract-only'
          ? 'Based on the research abstract only.'
          : ai.scope === 'permitted-transcript'
            ? 'Based on a permitted transcript.'
            : 'Based only on supplied source text.'}{' '}
        Generated by {ai.provider} · {ai.model}.
      </small>
      {ai.keyInsights.length > 0 && (
        <>
          <h3>Key insights</h3>
          <ul>
            {ai.keyInsights.map((insight, index) => (
              <li key={index}>{insight}</li>
            ))}
          </ul>
        </>
      )}
      <p>Intelligence type: {ai.intelligenceType?.replaceAll('_', ' ').toLowerCase()}.</p>
      <details>
        <summary>Scores and supporting evidence</summary>
        <p>
          Relevance: {ai.relevanceScore ?? 'Unavailable'} / 100 · Confidence:{' '}
          {ai.relevanceConfidence == null
            ? 'Unavailable'
            : `${Math.round(ai.relevanceConfidence * 100)}%`}
          .
        </p>
        <p>{ai.reason}</p>
        <p>
          Quality: {ai.qualityScore == null ? 'Unavailable' : `${ai.qualityScore} / 100`}.{' '}
          {ai.qualityReason}
        </p>
        <small>
          Model-assisted estimates of relevance and source detail, not verified publisher
          credibility.
        </small>
        {[...new Set([...ai.summaryEvidence, ...ai.insightEvidence])].map((quote, index) => (
          <blockquote key={index}>“{quote}”</blockquote>
        ))}
      </details>
    </section>
  );
}
